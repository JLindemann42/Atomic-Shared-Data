"""The study coach's scheduler (roadmap 2.6), as the reference both apps must match.

FSRS-5 with its published default parameters, rated Again (1) or Good (3), since a quiz answer is
only right or wrong. `python tools/fsrs_golden.py --write` regenerates golden/fsrs.tsv; without
--write it checks that the file is current. Android's `Fsrs.kt` and Windows' `Fsrs.cs` read the
same file in their tests, so a change to one scheduler without the other fails both.

See sync/study.md for the card keys and the wire format.
"""
import math
import sys
from pathlib import Path

W = [0.40255, 1.18385, 3.173, 15.69105, 7.1949, 0.5345, 1.4604, 0.0046, 1.54575, 0.1192,
     1.01925, 1.9395, 0.11, 0.29605, 2.2698, 0.2315, 2.9898, 0.51655, 0.6621]
DECAY = -0.5
FACTOR = 19.0 / 81.0
RETENTION = 0.9
DAY_MS = 86_400_000
MIN_STABILITY = 0.01
MAX_INTERVAL = 36_500


def clamp_difficulty(d):
    return min(max(d, 1.0), 10.0)


def initial_stability(g):
    return max(W[g - 1], MIN_STABILITY)


def initial_difficulty(g):
    return clamp_difficulty(W[4] - math.exp(W[5] * (g - 1)) + 1)


def retrievability(elapsed_days, s):
    return (1 + FACTOR * elapsed_days / s) ** DECAY


def interval_days(s):
    raw = s / FACTOR * (RETENTION ** (1 / DECAY) - 1)
    # Half up, written out: Python's round() is banker's, and the apps must agree to the day.
    return int(min(max(math.floor(raw + 0.5), 1), MAX_INTERVAL))


def next_difficulty(d, g):
    damped = d + (-W[6] * (g - 3)) * (10 - d) / 9
    return clamp_difficulty(W[7] * initial_difficulty(4) + (1 - W[7]) * damped)


def recall_stability(d, s, r, g):
    hard = W[15] if g == 2 else 1.0
    easy = W[16] if g == 4 else 1.0
    return s * (math.exp(W[8]) * (11 - d) * s ** (-W[9]) * (math.exp(W[10] * (1 - r)) - 1) * hard * easy + 1)


def forget_stability(d, s, r):
    return min(W[11] * d ** (-W[12]) * ((s + 1) ** W[13] - 1) * math.exp(W[14] * (1 - r)), s)


def same_day_stability(s, g):
    return s * math.exp(W[17] * (g - 3 + W[18]))


def review(card, g, now_ms):
    """card: None or dict(s, d, due, last, reps, lapses). Returns the new card."""
    if card is None:
        s, d, reps, lapses = initial_stability(g), initial_difficulty(g), 1, 1 if g == 1 else 0
    else:
        elapsed = (now_ms - card['last']) / DAY_MS
        if elapsed < 1:
            s = same_day_stability(card['s'], g)
        else:
            r = retrievability(elapsed, card['s'])
            s = recall_stability(card['d'], card['s'], r, g) if g > 1 else forget_stability(card['d'], card['s'], r)
        d = next_difficulty(card['d'], g)
        reps, lapses = card['reps'] + 1, card['lapses'] + (1 if g == 1 else 0)
    s = max(s, MIN_STABILITY)
    ivl = interval_days(s)
    return dict(s=s, d=d, due=now_ms + ivl * DAY_MS, last=now_ms, reps=reps, lapses=lapses, ivl=ivl)


START = 1_700_000_000_000

# Each case: (elapsed days since the previous review, rating). The first elapsed is ignored.
CASES = {
    'good-streak': [(0, 3), (1, 3), (3, 3), (8, 3), (20, 3), (50, 3)],
    'first-miss': [(0, 1), (1, 3), (1, 3), (4, 3)],
    'lapse': [(0, 3), (3, 3), (9, 1), (1, 3), (3, 3)],
    'double-lapse': [(0, 3), (2, 1), (1, 1), (1, 3), (2, 3)],
    'same-day': [(0, 3), (0.2, 3), (0.5, 1), (1, 3)],
    'late': [(0, 3), (3, 3), (40, 3), (200, 3)],
    'late-miss': [(0, 3), (5, 3), (90, 1), (1, 3)],
    'early': [(0, 3), (1, 3), (1, 3), (1, 3), (1, 3)],
    'long': [(0, 3)] + [(30, 3)] * 6 + [(400, 3)],
}


def golden_text():
    lines = [
        '# FSRS-5 vectors for the study coach (roadmap 2.6). Generated by tools/fsrs_golden.py; do not edit.',
        '# Each row is one review of the case\'s card: elapsed days since the previous review (ignored on the',
        '# first), the rating (1 Again, 3 Good), and the card after it. Apps compare s and d to 1e-9 relative,',
        '# interval exactly.',
        'case\tstep\telapsed_days\trating\tstability\tdifficulty\tinterval_days\treps\tlapses',
    ]
    for name, steps in CASES.items():
        card, now = None, START
        for i, (elapsed, g) in enumerate(steps):
            if i > 0:
                now += int(round(elapsed * DAY_MS))
            card = review(card, g, now)
            lines.append('\t'.join([name, str(i), repr(float(elapsed)), str(g), repr(card['s']), repr(card['d']),
                                    str(card['ivl']), str(card['reps']), str(card['lapses'])]))
    return '\n'.join(lines) + '\n'


def main():
    path = Path(__file__).resolve().parent.parent / 'golden' / 'fsrs.tsv'
    text = golden_text()
    if '--write' in sys.argv:
        path.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', path)
        return 0
    if not path.exists() or path.read_text(encoding='utf-8') != text:
        print('golden/fsrs.tsv is out of date: run tools/fsrs_golden.py --write')
        return 1
    print('golden/fsrs.tsv is current')
    return 0


if __name__ == '__main__':
    sys.exit(main())
